CREATE TABLE IF NOT EXISTS usuarios (
 id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 password VARCHAR(100) NOT NULL,
 removido BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS pacientes (
 id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL CHECK (length(trim(nome)) > 0),
 telefone VARCHAR(30) NOT NULL DEFAULT '',
 datanascimento DATE NOT NULL,
 removido BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS consultas (
 id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 pacienteid INTEGER NOT NULL REFERENCES pacientes(id),
 descricao VARCHAR(240) NOT NULL CHECK (length(trim(descricao)) > 0),
 dataconsulta DATE NOT NULL,
 valor NUMERIC(10,2) NOT NULL CHECK(valor>=0),
 removido BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_consultas_paciente_ativo ON consultas(pacienteid) WHERE removido=FALSE;
